"""Replay scorecard: would WeatherWise have warned before real past disasters?

Backtests every event in headline_events.toml and more_events.toml with the forecasts as they
were issued at the time (Open-Meteo archive; needs the network) and writes one table, misses
included, to evals/results/REPLAYS.md.

Usage:
    uv run python -m evals.eval_replays
"""

import tomllib
from datetime import date
from pathlib import Path

from scripts.backtest import run_one
from weatherwise.backtest.verification import verify
from weatherwise.mcp_server.services import ClimateRiskServices
from weatherwise.weather import ATTRIBUTION

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results" / "REPLAYS.md"
SIGNALS = {
    "heat": ["heat_wave", "excess_heat", "work_heat:take_care", "work_heat:danger"],
    "flood": ["flood_guide", "very_heavy_rain", "unusual_rain", "river_flood"],
}
FLOOD_WORDS = ("flood", "landslide", "rain", "cyclone")


def events() -> list[dict]:
    out = []
    for name in ("headline_events.toml", "more_events.toml"):
        for r in tomllib.loads((HERE / name).read_text())["replay"]:
            r.setdefault("kind", "flood" if any(w in r["title"].lower() for w in FLOOD_WORDS) else "heat")
            out.append(r)
    return out


def headline(r: dict, scores: dict) -> str:
    """Floods: days the flood guide was on before the day it happened (event_day).
    Heat: the heat-wave warning before the first hot spell, else what we did catch. A spell
    already under way on the replay's first day cannot be warned of, so it is not counted."""
    kind, event_day = r["kind"], r.get("event_day")
    if kind == "flood":
        s = scores.get("flood_guide") or {"event_lead_days": []}
        day = date.fromisoformat(event_day)
        before = [(date.fromisoformat(str(start)), lead) for start, lead in s["event_lead_days"]
                  if date.fromisoformat(str(start)) <= day]
        start, lead = max(before) if before else (None, None)
        return f"**warned {lead + (day - start).days} days ahead**" if lead else "**missed**"
    spells = sorted((date.fromisoformat(str(start)), lead) for name in ("heat_wave", "excess_heat")
                    for start, lead in (scores.get(name) or {"event_lead_days": []})["event_lead_days"]
                    if str(start) != r["first_day"])
    hits = sum((scores.get(name) or {}).get("hits", 0) for name in ("heat_wave", "excess_heat"))
    if spells and spells[0][1]:
        return f"**warned {spells[0][1]} days ahead**"
    later = [lead for _, lead in spells[1:] if lead]
    if later:
        return f"**first spell caught on the day; a later one {later[0]} days ahead**"
    return "**caught on the day, not ahead**" if hits else "**missed**"


def summary(r: dict, v: dict) -> tuple[str, str]:
    """(headline, detail) for one event."""
    if "scores" not in v:
        met = sorted({e for evs in v.get("conditions_met", {}).values() for e in evs})
        return "conditions only", "No archived forecasts this early; the real conditions met: " + (", ".join(met) or "none")
    parts = []
    for name in SIGNALS[r["kind"]]:
        s = v["scores"].get(name)
        if not s or not (s["hits"] or s["misses"] or s["false_alarms"]):
            continue
        leads = [f"{start} ({lead} d ahead)" if lead else f"{start} (not ahead)" for start, lead in s["event_lead_days"]]
        parts.append(f"{name}: {s['hits']} / {s['misses']} / {s['false_alarms']}; events " + ", ".join(leads))
    return headline(r, v["scores"]), "; ".join(parts) or "no signal fired"


def main() -> None:
    services = ClimateRiskServices.default()
    rows = []
    for r in events():
        _, bt = run_one(services, r["lat"], r["lon"], date.fromisoformat(r["first_day"]),
                            date.fromisoformat(r["last_day"]), r["name"])
        result, detail = summary(r, verify(bt))
        rows.append((r, result, detail))
        print(f"{r['title']}: {result.strip('*')}")

    lines = [
        "# Replay scorecard",
        "",
        "Generated by `uv run python -m evals.eval_replays`. Each event is replayed day by day with the",
        "forecasts **as they were issued at the time**, so nothing from after the day is used.",
        "\"Warned N days ahead\" means our flood guide or heat warning was on N days before the event",
        "started. Official warnings are not archived, so only our own signals are scored. In real",
        "use, official warnings are shown first and cover what we miss.",
        "",
        "| Event | Kind | Result | Signals (hits / misses / false alarms) | Reported |",
        "|---|---|---|---|---|",
    ]
    for r, result, detail in rows:
        lines.append(f"| {r['title']} | {r['kind']} | {result} | {detail} | {r['reported']} |")
    lines += ["", ATTRIBUTION]
    RESULTS.parent.mkdir(exist_ok=True)
    RESULTS.write_text("\n".join(lines) + "\n")
    print(f"Wrote {RESULTS}")


if __name__ == "__main__":
    main()
